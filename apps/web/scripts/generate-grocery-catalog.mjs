import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const sourcePath = process.argv[2];
const outputPath = process.argv[3];

if (!sourcePath || !outputPath) {
  throw new Error('Usage: node generate-grocery-catalog.mjs <manifest.json> <output.ts>');
}

const manifest = JSON.parse(await readFile(resolve(sourcePath), 'utf8'));

const categoryOrder = [
  'Produce',
  'Meat & Poultry',
  'Seafood',
  'Dairy & Eggs',
  'Bakery & Bread',
  'Pasta, Rice & Grains',
  'Canned & Jarred',
  'Condiments & Sauces',
  'Spices & Seasonings',
  'Baking',
  'Nuts, Seeds & Dried Fruit',
  'Frozen',
  'Snacks & Breakfast',
  'Beverages',
  'Pantry & Other',
  'Household'
];

const pantryCategories = {
  baking: 'Baking',
  'baking decoration': 'Baking',
  canned: 'Canned & Jarred',
  chocolate: 'Baking',
  'cooked legumes': 'Canned & Jarred',
  'cooking-wines': 'Condiments & Sauces',
  crackers: 'Snacks & Breakfast',
  extracts: 'Baking',
  flours: 'Baking',
  oils: 'Condiments & Sauces',
  olives: 'Canned & Jarred',
  'plant-based spreads': 'Condiments & Sauces',
  preserves: 'Canned & Jarred',
  'soy sauces': 'Condiments & Sauces',
  starches: 'Baking',
  sweeteners: 'Baking',
  syrups: 'Baking'
};

function categoryFor(record) {
  if (record.category === 'bakery' && record.subcategory === 'baking') return 'Baking';
  if (record.category === 'pantry' && record.subcategory in pantryCategories) {
    return pantryCategories[record.subcategory];
  }

  return {
    bakery: 'Bakery & Bread',
    beverages: 'Beverages',
    condiments: 'Condiments & Sauces',
    dairy: 'Dairy & Eggs',
    frozen: 'Frozen',
    grains: 'Pasta, Rice & Grains',
    herbs: 'Produce',
    household: 'Household',
    legumes: 'Pasta, Rice & Grains',
    meat: 'Meat & Poultry',
    nuts: 'Nuts, Seeds & Dried Fruit',
    pantry: 'Pantry & Other',
    personal: 'Household',
    pet: 'Household',
    produce: 'Produce',
    seafood: 'Seafood',
    snacks: 'Snacks & Breakfast',
    spices: 'Spices & Seasonings'
  }[record.category] ?? 'Other';
}

function normalizeAlias(value) {
  return value
    .normalize('NFKD')
    .replace(/\p{Diacritic}/gu, '')
    .toLocaleLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .replace(/\s+/g, ' ');
}

const categoriesByAlias = new Map();
for (const record of Object.values(manifest.recordsBySlug)) {
  const category = categoryFor(record);
  const aliases = new Set([
    record.displayName,
    record.slug?.replaceAll('-', ' '),
    ...(record.aliases ?? [])
  ]);

  for (const value of aliases) {
    const alias = normalizeAlias(value ?? '');
    if (alias.length < 2) continue;
    const categories = categoriesByAlias.get(alias) ?? new Set();
    categories.add(category);
    categoriesByAlias.set(alias, categories);
  }
}

const aliasesByCategory = new Map(categoryOrder.map((category) => [category, []]));
for (const [alias, categories] of categoriesByAlias) {
  if (categories.size !== 1) continue;
  const [category] = categories;
  aliasesByCategory.get(category)?.push(alias);
}

const groups = categoryOrder
  .map((category) => [category, aliasesByCategory.get(category).sort()])
  .filter(([, aliases]) => aliases.length > 0);

const lines = [
  '// Generated by scripts/generate-grocery-catalog.mjs. Do not edit by hand.',
  '// Source: Ingredient Atlas v0.1.2 metadata (CC0-1.0).',
  '// https://github.com/ionmesca/ingredient-atlas',
  '',
  'export const GROCERY_CATEGORY_ALIAS_GROUPS: ReadonlyArray<readonly [string, string]> = [',
  ...groups.map(
    ([category, aliases]) => `  [${JSON.stringify(category)}, ${JSON.stringify(aliases.join('\n'))}],`
  ),
  '];',
  ''
];

await writeFile(resolve(outputPath), lines.join('\n'));
console.log(`Generated ${categoriesByAlias.size.toLocaleString()} grocery aliases across ${groups.length} categories.`);
